use anyhow::{Result, bail};
use clap::Parser;
use rusty_scanner::config::{AnchorDirsConfig, ScannerConfig};
use rusty_scanner::matcher::AnchorMatcher;
use rusty_scanner::orchestrator::execute_matched_files;
use rusty_scanner::scanner::discover_misc_videos;
use rusty_scanner::tui::state::{TriageApp, TuiExitOutcome};
use rusty_scanner::tui::ui::run_tui;
use std::collections::HashSet;
use std::path::PathBuf;

#[derive(Parser, Debug)]
#[command(
    name = "rusty_triage",
    version = "0.1.0",
    about = "Standalone interactive TUI for manually assigning unmatched video files and parent directories to anchors, learning aliases into anchors.yaml, creating new anchor folders, and executing via rusty_dedup + rusty_clean."
)]
struct Args {
    /// Optional miscellaneous directories or video files to scan if `-i / --input-list` is not used
    #[arg(value_name = "INPUTS")]
    inputs: Vec<PathBuf>,

    /// Path to the map-style anchors YAML file (defaults to `anchors.yaml` if present, else `anchor_dirs.yaml`)
    #[arg(short = 'a', long = "anchors")]
    anchors: Option<PathBuf>,

    /// Optional path to scanner_config.yaml
    #[arg(short = 'c', long = "config")]
    config: Option<PathBuf>,

    /// Input text file of unmatched video paths (e.g., `un.txt` or `misc_files.txt` generated by `rusty_scanner`)
    #[arg(short = 'i', long = "input-list", value_name = "UNMATCHED_TXT")]
    input_list: Option<PathBuf>,

    /// Output CSV path for staged manual assignments (compatible with `rusty_scanner --from-csv`)
    #[arg(short = 'o', long = "output-csv", default_value = "manual_matches.csv")]
    output_csv: PathBuf,

    /// Optional path to write remaining unassigned video paths when saving
    #[arg(short = 'u', long = "unmatched-out")]
    unmatched_out: Option<PathBuf>,

    /// Override output directory where per-run dedup/clean JSON reports and `execution_report.html` are saved when pressing `X`
    #[arg(long = "report-dir", value_name = "REPORTS_DIR")]
    report_dir: Option<PathBuf>,

    /// Enable verbose output during live execution (`X`)
    #[arg(short = 'v', long = "verbose", default_value_t = false)]
    verbose: bool,
}

fn resolve_default_anchors_path(explicit: Option<PathBuf>) -> PathBuf {
    if let Some(p) = explicit {
        return p;
    }
    let p_anchors = PathBuf::from("anchors.yaml");
    if p_anchors.is_file() {
        return p_anchors;
    }
    PathBuf::from("anchor_dirs.yaml")
}

fn main() -> Result<()> {
    let args = Args::parse();
    let anchors_path = resolve_default_anchors_path(args.anchors);
    let anchor_cfg = AnchorDirsConfig::load(&anchors_path)?;
    let (mut scanner_cfg, _) =
        ScannerConfig::load_or_default(args.config.as_deref(), args.verbose)?;
    if let Some(ref custom_rep_dir) = args.report_dir {
        scanner_cfg.reports.output_dir = custom_rep_dir.clone();
    }

    let initial_files: Vec<PathBuf> = if let Some(ref list_path) = args.input_list {
        TriageApp::load_unmatched_list_file(list_path)?
    } else if !args.inputs.is_empty() {
        let matcher = AnchorMatcher::new(&anchor_cfg.anchors, scanner_cfg.matching.clone());
        let candidates = discover_misc_videos(
            &args.inputs,
            &anchor_cfg.anchors,
            &scanner_cfg.video_extensions,
            &HashSet::new(),
            true,
            args.verbose,
        );
        let outcome = matcher.match_batch(&candidates);
        outcome
            .unmatched_files
            .into_iter()
            .map(|c| c.path)
            .collect()
    } else if PathBuf::from("un.txt").is_file() {
        TriageApp::load_unmatched_list_file(&PathBuf::from("un.txt"))?
    } else if PathBuf::from("misc_files.txt").is_file() {
        TriageApp::load_unmatched_list_file(&PathBuf::from("misc_files.txt"))?
    } else {
        bail!(
            "No unmatched input provided. Pass `-i un.txt` (or `-i misc_files.txt`) or pass misc directories `<INPUTS>...`."
        );
    };

    if initial_files.is_empty() {
        println!("0 unmatched video files to triage — everything is already matched!");
        return Ok(());
    }

    let mut app = TriageApp::new(
        anchors_path,
        args.output_csv.clone(),
        args.unmatched_out.clone(),
        anchor_cfg,
        scanner_cfg,
        initial_files,
    )?;

    let exit_outcome = run_tui(&mut app)?;

    if exit_outcome == TuiExitOutcome::ExecuteNow {
        let staged = app.build_staged_outcome();
        println!(
            "\nExecuting {} staged assignment(s) from {:?}...",
            staged.matched_files.len(),
            args.output_csv
        );
        let tools = app.scanner_cfg.resolve_tools()?;
        execute_matched_files(
            &staged.matched_files,
            &app.anchor_cfg,
            &app.scanner_cfg,
            &tools,
            args.verbose,
        )?;
        if let Some(ref u_out) = args.unmatched_out {
            let rem = rusty_scanner::csv_report::write_unmatched_files(
                &staged.unmatched_files,
                u_out,
            )?;
            println!("Updated {:?} with {} remaining unmatched file(s).", u_out, rem);
        }
    } else if app.assigned_count() > 0 {
        println!(
            "Saved/staged {} assignment(s). Run later with:\n  ./target/release/rusty_scanner -a {:?} --from-csv {:?}",
            app.assigned_count(),
            app.anchors_yaml_path,
            args.output_csv
        );
    }

    Ok(())
}
